FACTS = ([("academy", *row) for row in ACADEMY]
         + [("transfer", *row) for row in TRANSFER]
         + [("record", *row) for row in RECORD]
         + [("u21", *row) for row in U21])


def main():
    facts_path = ROOT / "data" / "facts.jsonl"
    facts_path.parent.mkdir(parents=True, exist_ok=True)
    eval_rows = []
    with open(facts_path, "w", encoding="utf-8") as f:
        for i, (kind, fact, q_orig, q_para, ans) in enumerate(FACTS):
            fid = f"f{i:02d}"
            f.write(json.dumps({"id": fid, "kind": kind, "fact": fact,
                                "question": q_orig, "answer": ans},
                               ensure_ascii=False) + "\n")
            eval_rows.append({"fact_id": fid, "kind": kind, "qkind": "orig",
                              "question": q_orig, "answer": ans})
            eval_rows.append({"fact_id": fid, "kind": kind, "qkind": "para",
                              "question": q_para, "answer": ans})
    eval_path = ROOT / "eval" / "facts_eval.jsonl"
    eval_path.parent.mkdir(parents=True, exist_ok=True)
    with open(eval_path, "w", encoding="utf-8") as f:
        for r in eval_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"facts: {len(FACTS)} -> {facts_path}; eval: {len(eval_rows)} -> eval/facts_eval.jsonl")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
