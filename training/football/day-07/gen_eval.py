def canon(d):
    d = dict(d)
    d["scorers"] = sorted(d["scorers"],
                          key=lambda x: (x["minute"], x["team"], x["player"]))
    return d


def main():
    rows = []
    seen = set()
    for text, gold in CASES:
        assert gold is not None, f"пустой gold у: {text[:50]}"
        assert text not in seen, f"дубль кейса: {text[:50]}"
        seen.add(text)
        rows.append({"id": f"eval-{len(rows):02d}", "prompt": text,
                     "gold": json.dumps(canon(gold), ensure_ascii=False,
                                        separators=(",", ":"))})
    out = ROOT / "eval" / "eval.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"eval: {len(rows)} кейсов -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
