// ЗАДАНИЕ:
//   Возьмите одну задачу (логическую, алгоритмическую или аналитическую).
//   Решите её через API четырьмя способами:
//   1. Прямой ответ без дополнительных инструкций
//   2. «решай пошагово»
//   3. Сначала составь промпт, затем используйте его
//   4. Группа экспертов (аналитик, инженер, критик), решение от каждого
//
//   Сравните: отличаются ли ответы, какой способ дал наиболее точный результат.

import { LlmClient, msg } from '../core/index.js';
import type { Demo } from './types.js';

const TASK =
  'У тебя есть 5 задач с приоритетами A (срочная), B (важная), ' +
  'C (рутина), D (делегируемая), E (можно удалить). ' +
  'Время ограничено 2 часами. Как оптимально распределить время?';

async function run(): Promise<void> {
  const client = new LlmClient();

  console.log('=== 1. Прямой ответ ===');
  console.log(await client.chat([msg.user(TASK)]) + '\n');

  console.log('=== 2. Пошаговое рассуждение ===');
  console.log(
    await client.chat([
      msg.user(TASK + '\n\nДумай пошагово, объясняй каждый шаг.'),
    ]) + '\n',
  );

  console.log('=== 3. Мета-промпт ===');
  console.log(
    await client.chat([
      msg.user(
        TASK +
          '\n\nСначала составь оптимальный промпт для решения этой задачи, ' +
          'выведи его под заголовком ПРОМПТ, затем примени его и дай ответ ' +
          'под заголовком ОТВЕТ.',
      ),
    ]) + '\n',
  );

  console.log('=== 4. Группа экспертов ===');
  console.log(
    await client.chat([
      msg.user(
        TASK +
          '\n\nПредставь команду из трёх экспертов:\n' +
          '- Аналитик: оценивает приоритеты\n' +
          '- Инженер: предлагает процесс\n' +
          '- Критик: проверяет на слабые места\n' +
          'Каждый даёт свою позицию, затем выведите общий итог.',
      ),
    ]),
  );
}

export const demo: Demo = {
  id: 'day-03',
  title: 'Разные способы рассуждения',
  run,
};
