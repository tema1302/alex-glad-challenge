/** Опции user-промпта: дайджест — только студия /antonov (вход длиннее порога). */
export interface StyleUserPromptOpts {
  digest?: boolean;
}

// Дайджест-блок студии: длинный исходник → сжатый пересказ, а не построчный
// рерайт. Явно отменяет «длина ±30%» из system-промпта; сжатие разрешено только
// выбрасыванием второстепенного — оставленное неприкосновенно (та же регрессия
// «коверканья смысла», что в system-инвариантах).
const DIGEST_RULES = `РЕЖИМ ДАЙДЖЕСТА: исходник длинный. Нужен не построчный рерайт, а выжимка голосом канала.
- Отбери главное: ключевые факты, цифры, имена, счёт, исходы событий и «кому выгодно» (если выгода есть в исходнике). Второстепенное — повторы, детали, лирику — выбрасывай без жалости.
- Сжатие — не искажение: всё оставшееся держи фактическим 1:1 (цифры, имена, хронология и исходы на своих местах), позиция автора исходника = твоя позиция, ничего от себя.
- Правило «длина сопоставима с исходником» здесь НЕ действует: итог — компактный пост, в несколько раз короче исходника (ориентир — до ~4000 знаков).`;

/** User-сообщение: параметры подачи + исходный текст. Промпт и модель — серверные. */
export function buildStyleUserPrompt(input: StyleRewriteInput, opts: StyleUserPromptOpts = {}): string {
  const signature = input.signature
    ? 'Да — заверши пост ритуальной подписью «Антоновайзер, быть добру. Подписаться.»'
    : 'Нет — без ритуальной подписи в конце.';
  return `Режим грубости: ${MODE_LABEL[input.mode]}.
Формат: ${FORMAT_LABEL[input.format]}.
Подпись: ${signature}
${opts.digest ? `\n${DIGEST_RULES}\n` : ''}
ТЕКСТ:
${input.text}`;
}
