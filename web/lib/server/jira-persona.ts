/** Ровно 7 заголовков выходного контракта; фиксированный порядок = чеклист validateJiraStory. */
export const JIRA_HEADERS = [
  'Заголовок / Summary',
  'Пользовательская история / User Story',
  'Бизнес-ценность / Business Value',
  'Предусловия / Preconditions',
  'Основной сценарий / Main Scenario',
  'Критерии приемки / Acceptance Criteria',
  'Ожидаемый результат / Expected Result',
] as const;

/**
 * Sanity-валидация выхода модели: все 7 заголовков присутствуют и идут в порядке
 * контракта. Валидация LLM-ответа перед потреблением — инвариант CLAUDE.md.
 * @returns null — контракт соблюдён; иначе человекочитаемая причина отказа.
 */
export function validateJiraStory(text: string): string | null {
  let pos = -1;
  for (const h of JIRA_HEADERS) {
    const idx = text.indexOf(h);
    if (idx < 0) return `в ответе модели нет раздела «${h}»`;
    if (idx <= pos) return 'разделы в ответе модели идут не по порядку';
    pos = idx;
  }
  return null;
}

